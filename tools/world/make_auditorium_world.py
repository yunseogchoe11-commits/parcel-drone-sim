"""강당 월드 생성 → worlds/auditorium.sdf, models/auditorium_floor/model.sdf

하는 일
  1. PX4 기본 월드(default.sdf)를 읽어 물리·플러그인·지구 좌표 설정을 그대로 가져온다.
     (PX4가 기대하는 설정이라 직접 만들지 않고 복사한다.)
  2. 회색 바닥(ground_plane)을 지우고 강당 바닥 모델(나무 마루 그림)을 넣는다.
  3. 벽 4개, H/D/P 표시(테두리), 택배 상자(P 위치, 그리고 PARCEL_AT_H면 H에도)를 넣는다.

설정값은 모두 tools/auditorium_config.py 에 있다. 그 파일만 고치고 이 스크립트를 다시 실행한다.
worlds/auditorium.sdf 를 직접 고치면 다시 생성할 때 덮어써진다.

사용: python3 tools/world/make_auditorium_world.py   (파이썬 기본 기능만 사용)
실행: PX4_GZ_WORLD=auditorium make px4_sitl gz_x500_flow
"""
import math
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # tools/ (auditorium_config.py 위치)
import auditorium_config as C  # noqa: E402

REPO = Path(__file__).resolve().parents[2]                       # 저장소 맨 위
PX4_DEFAULT_WORLD = Path.home() / "PX4-Autopilot/Tools/simulation/gz/worlds/default.sdf"
OUT_WORLD = REPO / "worlds/auditorium.sdf"
FLOOR_DIR = REPO / "models/auditorium_floor"

WALL_COLOR = "0.80 0.74 0.62 1"     # 베이지 (사진 1번 벽 색, 차분하게)
OUTSIDE_COLOR = "0.45 0.45 0.44 1"  # 강당 밖 바닥 (회색)


def to_world(x, y):
    """강당 좌표 → 월드 좌표 (원점 = H)."""
    return round(x - C.H[0], 4), round(y - C.H[1], 4)


def material(rgba):
    return f"<material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material>"


def box(name, x, y, z, sx, sy, sz, rgba, collision=False):
    """상자 모양 하나 (보이는 모양 + 필요하면 충돌 모양)."""
    geom = f"<geometry><box><size>{sx} {sy} {sz}</size></box></geometry>"
    pose = f"<pose>{x} {y} {z} 0 0 0</pose>"
    s = f'<visual name="{name}">{pose}{geom}{material(rgba)}</visual>'
    if collision:
        s += f'<collision name="{name}_col">{pose}{geom}</collision>'
    return s


# ── 바닥 모델 (models/auditorium_floor) ────────────────────────
def write_floor_model():
    """강당 크기에 맞춘 바닥 모델 파일을 쓴다. 그림은 make_floor_texture.py가 만든다."""
    config = f"""<?xml version="1.0"?>
<model>
  <name>auditorium_floor</name>
  <version>2.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>Auditorium wood floor {C.HALL_W:g} x {C.HALL_D:g} m (generated by tools/world/make_auditorium_world.py)</description>
</model>
"""
    sdf = f"""<?xml version="1.0" encoding="UTF-8"?>
<sdf version="1.9">
  <!-- tools/world/make_auditorium_world.py 가 생성. 직접 수정 금지 -->
  <!-- 강당 바닥 {C.HALL_W:g} x {C.HALL_D:g} m, 나무 마루 그림. 모델 원점 = 강당 중앙 -->
  <model name="auditorium_floor">
    <static>true</static>
    <link name="link">
      <!-- 충돌면: 넉넉하게 200 x 200 m -->
      <collision name="collision">
        <geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
        <surface><friction><ode><mu>0.8</mu><mu2>0.8</mu2></ode></friction></surface>
      </collision>
      <!-- 강당 바닥 그림 -->
      <visual name="wood">
        <geometry><plane><normal>0 0 1</normal><size>{C.HALL_W} {C.HALL_D}</size></plane></geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <specular>0.1 0.1 0.1 1</specular>
          <pbr><metal>
            <albedo_map>model://auditorium_floor/materials/textures/{C.FLOOR_TEXTURE}</albedo_map>
            <roughness>0.6</roughness>
            <metalness>0.0</metalness>
          </metal></pbr>
        </material>
      </visual>
      <!-- 강당 밖 바닥 (회색, 살짝 아래) -->
      <visual name="outside">
        <pose>0 0 -0.005 0 0 0</pose>
        <geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
        {material(OUTSIDE_COLOR)}
      </visual>
    </link>
  </model>
</sdf>
"""
    FLOOR_DIR.mkdir(parents=True, exist_ok=True)
    (FLOOR_DIR / "model.config").write_text(config, encoding="utf-8")
    (FLOOR_DIR / "model.sdf").write_text(sdf, encoding="utf-8")


# ── 월드에 넣을 것들 ──────────────────────────────────────────
def world_items():
    items = []
    cx, cy = to_world(C.HALL_W / 2, C.HALL_D / 2)       # 강당 중앙 (월드 좌표)

    # 1) 바닥
    items.append(f"<include><uri>model://auditorium_floor</uri><name>floor</name>"
                 f"<pose>{cx} {cy} 0 0 0 0</pose></include>")

    # 2) 벽 4개 (강당 바깥 둘레, 충돌 있음)
    x0, y0 = to_world(0, 0)
    x1, y1 = to_world(C.HALL_W, C.HALL_D)
    t, h = C.WALL_T, C.WALL_H
    long_ = C.HALL_W + 2 * t
    walls = (box("north", cx, y1 + t / 2, h / 2, long_, t, h, WALL_COLOR, True) +
             box("south", cx, y0 - t / 2, h / 2, long_, t, h, WALL_COLOR, True) +
             box("west", x0 - t / 2, cy, h / 2, t, C.HALL_D, h, WALL_COLOR, True) +
             box("east", x1 + t / 2, cy, h / 2, t, C.HALL_D, h, WALL_COLOR, True))
    items.append(f'<model name="walls"><static>true</static><link name="link">{walls}</link></model>')

    # 3) H/D/P 표시: 테두리 4변만 (보이기만 하고 충돌 없음, 두께 2 mm)
    for name, pos in (("H", C.H), ("D", C.D), ("P", C.P)):
        x, y = to_world(*pos)
        a, w, z, rgba = C.PAD_SIZE / 2, C.PAD_LINE, 0.001, C.PAD_COLOR[name]
        frame = (box("n", x, y + a, z, C.PAD_SIZE, w, 0.002, rgba) +
                 box("s", x, y - a, z, C.PAD_SIZE, w, 0.002, rgba) +
                 box("e", x + a, y, z, w, C.PAD_SIZE, 0.002, rgba) +
                 box("w", x - a, y, z, w, C.PAD_SIZE, 0.002, rgba))
        items.append(f'<model name="pad_{name}"><static>true</static><link name="link">{frame}</link></model>')

    # 4) 택배 상자: P에 놓인 것 (parcel, 태그 id 0) + 첫 택배 B (parcel_H, 태그 id 1). 태그는 add_apriltag.py가 붙임
    bx, by, bz = C.PARCEL_SIZE
    m = C.PARCEL_MASS
    ixx, iyy, izz = m / 12 * (by**2 + bz**2), m / 12 * (bx**2 + bz**2), m / 12 * (bx**2 + by**2)
    geom = f"<geometry><box><size>{bx} {by} {bz}</size></box></geometry>"
    spots = [("parcel", C.P, "0.55 0.42 0.30 1")]
    if getattr(C, "PARCEL_AT_H", False):
        spots.append(("parcel_H", getattr(C, "B", C.H), "0.62 0.50 0.36 1"))
    for name, pos, rgba in spots:
        px, py = to_world(*pos)
        items.append(
            f'<model name="{name}"><pose>{px} {py} {bz / 2} 0 0 {math.radians(getattr(C, "PARCEL_YAW", 0.0)):.6f}</pose><link name="link">'
            f'<inertial><mass>{m}</mass><inertia><ixx>{ixx:.6f}</ixx><iyy>{iyy:.6f}</iyy><izz>{izz:.6f}</izz>'
            f'<ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia></inertial>'
            f'<collision name="col">{geom}<surface><friction><ode><mu>{C.PARCEL_MU}</mu>'
            f'<mu2>{C.PARCEL_MU}</mu2></ode></friction></surface></collision>'
            f'<visual name="vis">{geom}{material(rgba)}</visual></link></model>')
    return items


def main():
    write_floor_model()

    tree = ET.parse(PX4_DEFAULT_WORLD)
    world = tree.getroot().find("world")
    world.set("name", "auditorium")        # 파일 이름(auditorium.sdf)과 같아야 PX4가 연결함
    for m in list(world.findall("model")):
        if m.get("name") == "ground_plane":
            world.remove(m)                  # 기본 회색 바닥 제거
    for s in world_items():
        world.append(ET.fromstring(s))

    ET.indent(tree, space="  ")
    OUT_WORLD.parent.mkdir(parents=True, exist_ok=True)
    tree.write(OUT_WORLD, encoding="utf-8", xml_declaration=True)

    print("저장:", OUT_WORLD)
    print(f"강당 {C.HALL_W:g} x {C.HALL_D:g} m")
    for n, p in (("H", C.H), ("D", C.D), ("P", C.P)):
        print(f"  {n}: 강당 {p} → 월드 {to_world(*p)}")


if __name__ == "__main__":
    main()
